"""Open-data opacity and ion-balance models against reference data (results/atomic_lines/).

1. Rosseland and Planck means from the NIST-based model (aegis/tabular.py) against Los Alamos TOPS for Al and Cu on the
   bundled TOPS grid (T 10 eV - 1 keV, rho 1e-3, 1e-2, 1e-1 g/cc, LTE), for several line treatments: none, the
   screened-hydrogenic line model, NIST lines, and CHIANTI lines (Al, if downloaded with --chianti).
2. Coronal (low-density) mean charge from the collisional-radiative balance against CHIANTI's ion equilibrium, without
   dielectronic recombination, with CHIANTI's fitted DR rates, and with the Burgess General Formula.

    python examples/atomic_vs_tops.py [--chianti] [--step 1]
"""
import os
import sys
import argparse

import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, "tools"))
import atomic_importer as ai                     # noqa: E402
from aegis import tabular as tb                  # noqa: E402


def factor(model, ref):
    lr = np.log(model / ref)
    return float(np.exp(np.mean(np.abs(lr)))), float(np.exp(np.mean(lr))), float(np.mean(np.abs(lr) < np.log(1.05))), \
        float(np.mean(np.abs(lr) < np.log(2.0)))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--chianti", action="store_true", help="also CHIANTI lines for Al (downloads about 7 MB)")
    ap.add_argument("--step", type=int, default=1, help="use every step-th TOPS point")
    ap.add_argument("--out", default=os.path.join(ROOT, "results", "atomic_lines"))
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    E = np.geomspace(0.05, 2e5, 4000)
    rows, summary = [], []
    for e in ("Al", "Cu"):
        Z, A = ai.Z_OF[e], ai.A_OF[e]
        I = ai.fetch_nist_ie(e)
        d = ai.load_tops_csv(os.path.join(ai.DATA, f"tops_{e}.csv"))[::a.step]
        sb = tb._bf_cross_sections(tb.fill_ionization(I), Z, E)
        variants = {"none": dict(), "model": dict(line_model=True), "NIST": dict(lines=ai.fetch_nist_lines(e))}
        if a.chianti and e == "Al":
            variants["CHIANTI"] = dict(lines=ai.fetch_chianti_lines(e))
        res = {k: [] for k in variants}
        for Tk, r, kr, kp, zf, z2 in d:
            f, ne, zb = tb.saha_balance(I, A, np.array(r * 1e3), np.array(Tk * 1e3))
            for k, kw in variants.items():
                ka, ke = tb.atomic_opacity(I, Z, A, r * 1e3, Tk * 1e3, f, float(ne), E, sigma_bf=sb, **kw)
                pP, pR = tb.group_means(ka, ke, E, Tk * 1e3, np.array([0.0, np.inf]))
                res[k].append((pR[0], pP[0]))
                rows.append((e, k, Tk, r, kr, pR[0], kp, pP[0], zf, float(zb)))
        for k, v in res.items():
            v = np.array(v)
            fr, br, w5r, w2r = factor(v[:, 0], d[:, 2])
            fp, bp, w5p, w2p = factor(v[:, 1], d[:, 3])
            summary.append(f"| {e} | {k} | {fr:.1f} (x{br:.2f}) | {w5r:.0%} | {w2r:.0%} | {fp:.1f} (x{bp:.2f}) | {w5p:.0%} | {w2p:.0%} |")
            print(summary[-1])
    with open(os.path.join(a.out, "opacity_vs_tops.csv"), "w", encoding="utf-8", newline="\n") as f:
        f.write("element,lines,T_keV,rho_gcc,kR_tops,kR_model,kP_tops,kP_model,Zfree_tops,Zbar_saha\n")
        for r in rows:
            f.write(",".join([r[0], r[1]] + [f"{x:.6g}" for x in r[2:]]) + "\n")
    dr_lines = []
    for e in ("Al", "Cu"):
        Z, A = ai.Z_OF[e], ai.A_OF[e]
        I = ai.fetch_nist_ie(e)
        Tc, Fc = ai.load_chianti_ioneq(Z)
        zc = np.arange(Z + 1) @ Fc
        s = (zc > 0.3) & (zc < Z - 0.3)
        out = []
        for name, kw in (("none", dict()), ("CHIANTI fits", dict(dr="chianti", dr_table=ai.fetch_chianti_dr(e))),
                         ("Burgess GF", dict(dr="burgess"))):
            zb = tb.cr_balance(I, Z, A, np.full(s.sum(), 1e-8), Tc[s], **kw)[2]
            out.append(f"{np.mean(np.abs(zb - zc[s])):.2f} (max {np.max(np.abs(zb - zc[s])):.2f})")
        dr_lines.append(f"| {e} | " + " | ".join(out) + " |")
        print(dr_lines[-1])
    with open(os.path.join(a.out, "summary.md"), "w", encoding="utf-8", newline="\n") as f:
        f.write("# Open-data opacity and ion balance against reference data\n\n"
                "Generated by `python examples/atomic_vs_tops.py" + (" --chianti" if a.chianti else "") + "`.\n\n"
                "## Rosseland and Planck means against Los Alamos TOPS (LTE, T 10 eV - 1 keV, rho 1e-3 - 1e-1 g/cc)\n\n"
                "Typical factor off = exp(mean |ln(model / TOPS)|); bias = exp(mean ln(model / TOPS)), below 1 is low.\n\n"
                "| element | lines | kappa_R factor (bias) | within 5% | within 2x | kappa_P factor (bias) | within 5% | within 2x |\n"
                "|---|---|---|---|---|---|---|---|\n" + "\n".join(summary) + "\n\n"
                "## Coronal mean charge against CHIANTI ion equilibrium: mean |Z_bar - Z_bar(CHIANTI)|\n\n"
                "| element | no dielectronic recombination | CHIANTI DR fits | Burgess General Formula (model core lines) |\n"
                "|---|---|---|---|\n" + "\n".join(dr_lines) + "\n")


if __name__ == "__main__":
    main()
